import fs from "node:fs";
import Ajv2020 from "ajv/dist/2020.js";
import standalone from "ajv/dist/standalone/index.js";
const schema = JSON.parse(
  fs.readFileSync(new URL("../src/schemas/compose-spec.json", import.meta.url)),
);
const ajv = new Ajv2020({
  allErrors: true,
  strict: false,
  validateFormats: false,
  code: { source: true, esm: true },
});
let output = standalone(ajv, ajv.compile(schema));
const imports = new Map();
output = output.replace(/require\("([^"]+)"\)\.default/g, (_, path) => {
  if (!imports.has(path)) imports.set(path, `runtime${imports.size}`);
  return imports.get(path);
});
if (output.includes("require("))
  throw new Error("Unexpected runtime dependency in standalone validator");
output =
  [...imports]
    .map(
      ([path, name]) =>
        `import ${name}Module from "${path}.js"; const ${name} = ${name}Module.default ?? ${name}Module;`,
    )
    .join("\n") +
  "\n" +
  output;
fs.writeFileSync(
  new URL("../src/generated/composeValidator.js", import.meta.url),
  "// Generated by scripts/generate-compose-validator.mjs. No runtime eval or network.\n" +
    output,
);
